"""Render validated zone policies as a complete OpenBSD PF ruleset."""

from ipaddress import ip_network
from pathlib import Path

from .model import Config, RESERVED, Rule, Selector, subtract_networks


FAMILIES = ("inet", "inet6")


def _list(values):
    values = tuple(dict.fromkeys(values))
    return values[0] if len(values) == 1 else "{ " + ", ".join(values) + " }"


def _table(zone, family):
    return f"mp_{zone}_{'4' if family == 'inet' else '6'}"


class _Renderer:
    def __init__(self, config):
        self.config = config
        self.lines = []
        self.interfaces = tuple(config.interfaces.values())
        self.zone_interfaces = {
            name: tuple(interface for interface in self.interfaces if interface.zone == name)
            for name in config.zones
        }
        self.networks = {
            (name, family): tuple(dict.fromkeys(
                interface.network(family) for interface in self.zone_interfaces[name]
                if interface.network(family) is not None
            ))
            for name in config.zones for family in FAMILIES
        }

    def section(self, title):
        if self.lines:
            self.lines.append("")
        self.lines.append(f"# {title}")

    def zone_names(self, name, family):
        names = self.config.zones if name == "all" else (name,)
        return tuple(name for name in names if family in self.config.zones[name].families
                     and (name == self.config.firewall or self.networks[name, family]))

    def addresses(self, selector, zone, family):
        """Intersect literal selectors with their zone before emitting PF lists."""
        if selector.address == "any":
            if zone == self.config.firewall:
                return "any"
            return f"<{_table(zone, family)}>"
        if selector.address.startswith("@"):
            selected = self.config.groups[selector.address[1:]].networks
        else:
            selected = (selector.address,)
        version = 4 if family == "inet" else 6
        selected = [ip_network(network) for network in selected
                    if ip_network(network).version == version]
        if zone == self.config.firewall:
            return _list(str(network) for network in selected) if selected else None
        zone_networks = self.networks[zone, family]
        if "any" in zone_networks:
            excluded = [ip_network(network) for (other, af), networks in self.networks.items()
                        if af == family and other != zone for network in networks
                        if network != "any"]
            excluded.extend(ip_network(network) for network in RESERVED[family])
            selected = subtract_networks(selected, excluded)
        else:
            selected = [small if small.subnet_of(large) else large
                        for small in selected for large in map(ip_network, zone_networks)
                        if small.overlaps(large)]
        return _list(str(network) for network in sorted(set(selected))) if selected else None

    def options(self):
        self.lines.extend(("# Generated by MakePF. Review before loading.",
                           "set block-policy drop", "set state-policy if-bound"))
        if self.config.settings.get("loopback", ("yes",)) == ("yes",):
            self.lines.append("set skip on lo0")
        if "loginterface" in self.config.settings:
            zone = self.config.settings["loginterface"][0]
            self.lines.append("set loginterface " + self.zone_interfaces[zone][0].name)
        self.section("Zone addresses")
        for name in self.config.zones:
            if name == self.config.firewall:
                continue
            for family in FAMILIES:
                networks = self.networks[name, family]
                if not networks:
                    continue
                if "any" in networks:
                    entries = ["0.0.0.0/0" if family == "inet" else "::/0"]
                    excluded = list(RESERVED[family])
                    for (other, af), other_networks in self.networks.items():
                        if af == family and other != name:
                            excluded.extend(network for network in other_networks if network != "any")
                    entries.extend("!" + network for network in dict.fromkeys(excluded))
                else:
                    entries = list(networks)
                self.lines.append(f"table <{_table(name, family)}> const {{ " + ", ".join(entries) + " }")
        self.section("Default deny")
        self.lines.append("block all")
        scrub = []
        if self.config.settings.get("normalize") == ("yes",):
            scrub.extend(("no-df", "random-id", "reassemble tcp"))
        if "mss" in self.config.settings:
            scrub.append("max-mss " + self.config.settings["mss"][0])
        if scrub:
            self.lines.append("match in all scrub (" + " ".join(scrub) + ")")
        self.lines.append("block in quick from (self) to any")

    def controls(self):
        self.section("Explicit link services")
        for interface in self.interfaces:
            zone, name = interface.zone, interface.name
            if interface.ipv4:
                network = f"<{_table(zone, 'inet')}>"
                if zone in self.config.settings.get("dhcp-server", ()):
                    self.lines.extend((
                        f"pass in quick on {name} inet proto udp from 0.0.0.0 port 68 to 255.255.255.255 port 67 no state",
                        f"pass in quick on {name} inet proto udp from {network} port 68 to {{ ({name}), ({name}:broadcast), 255.255.255.255 }} port 67 no state",
                        f"pass out quick on {name} inet proto udp from ({name}) port 67 to {{ {network}, 255.255.255.255 }} port 68 ! received-on any no state",
                    ))
                if zone in self.config.settings.get("dhcp-client", ()):
                    self.lines.extend((
                        f"pass out quick on {name} inet proto udp from {{ 0.0.0.0, ({name}) }} port 68 to any port 67 ! received-on any no state",
                        f"pass in quick on {name} inet proto udp from {network} port 67 to {{ ({name}), ({name}:broadcast), 255.255.255.255 }} port 68 no state",
                    ))
            roles = tuple(role for role in ("ipv6-neighbor", "ipv6-router", "ipv6-client")
                          if zone in self.config.settings.get(role, ()))
            if interface.ipv6 and roles:
                network = f"<{_table(zone, 'inet6')}>"
                self.lines.extend((
                    f"pass in quick on {name} inet6 proto icmp6 from {{ ::, fe80::/10, {network} }} to {{ ({name}), ff02::1:ff00:0/104 }} icmp6-type 135 no state",
                    f"pass in quick on {name} inet6 proto icmp6 from {{ fe80::/10, {network} }} to {{ ({name}), ff02::1 }} icmp6-type 136 no state",
                    f"pass out quick on {name} inet6 proto icmp6 from {{ ::, ({name}) }} to any icmp6-type {{ 135, 136 }} ! received-on any no state",
                    f"pass in quick on {name} inet6 proto icmp6 from {{ ::, fe80::/10 }} to ff02::/16 icmp6-type {{ 130, 131, 132, 143 }} allow-opts no state",
                    f"pass out quick on {name} inet6 proto icmp6 from {{ ::, ({name}) }} to ff02::/16 icmp6-type {{ 130, 131, 132, 143 }} ! received-on any allow-opts no state",
                ))
                if "ipv6-router" in roles:
                    self.lines.extend((
                        f"pass in quick on {name} inet6 proto icmp6 from {{ ::, fe80::/10, {network} }} to {{ ({name}), ff02::2 }} icmp6-type 133 no state",
                        f"pass out quick on {name} inet6 proto icmp6 from fe80::/10 to {{ ff02::1, fe80::/10, {network} }} icmp6-type 134 ! received-on any no state",
                    ))
                if "ipv6-client" in roles:
                    self.lines.extend((
                        f"pass in quick on {name} inet6 proto icmp6 from fe80::/10 to {{ ({name}), ff02::1 }} icmp6-type 134 no state",
                        f"pass out quick on {name} inet6 proto icmp6 from {{ ::, ({name}) }} to ff02::2 icmp6-type 133 ! received-on any no state",
                    ))
            if self.config.settings.get("icmp-errors") == ("yes",):
                for family in FAMILIES:
                    if not interface.network(family):
                        continue
                    protocol = "icmp" if family == "inet" else "icmp6"
                    types = "{ 3, 11, 12 }" if family == "inet" else "{ 1, 2, 3, 4 }"
                    keyword = "icmp-type" if family == "inet" else "icmp6-type"
                    source = f"<{_table(zone, family)}>"
                    if family == "inet6":
                        source = "{ " + source + ", fe80::/10 }"
                    self.lines.extend((
                        f"pass in quick on {name} {family} proto {protocol} from {source} to (self) {keyword} {types} no state",
                        f"pass out quick on {name} {family} proto {protocol} from (self) to any {keyword} {types} ! received-on any no state",
                    ))

    def guards(self):
        self.section("Source validation and non-routed addresses")
        for interface in self.interfaces:
            for family in FAMILIES:
                if interface.network(family):
                    self.lines.append(f"block in quick on {interface.name} {family} from ! <{_table(interface.zone, family)}> to any")
        for family in FAMILIES:
            self.lines.append(f"block in quick {family} to {_list(RESERVED[family])}")

    def transport(self, rule):
        if rule.protocol == "any":
            return "", ""
        protocol = " proto " + rule.protocol
        if rule.service == "-":
            return protocol, ""
        if rule.protocol in ("tcp", "udp"):
            return protocol, " port " + _list(rule.service.split(","))
        keyword = "icmp-type" if rule.protocol == "icmp" else "icmp6-type"
        return protocol, " " + keyword + " " + rule.service

    def filter(self, rule, source_zone, destination_zone, family, direction,
               interface, source, destination, extra=""):
        protocol, service = self.transport(rule)
        hosts = f"from {source} to {destination}"
        if rule.protocol in ("tcp", "udp"):
            hosts += service
            service = ""
        action = {"ACCEPT": "pass", "DROP": "block drop", "REJECT": "block return"}[rule.action]
        log = " log" if rule.log else ""
        no_state = rule.protocol in ("icmp", "icmp6") and rule.service != "-" and (
            int(rule.service) != (8 if rule.protocol == "icmp" else 128)
        )
        state = (" no state" if no_state else " keep state (if-bound)") if rule.action == "ACCEPT" else ""
        nat = ""
        if direction == "out" and family == "inet" and rule.action == "ACCEPT" and not no_state:
            if any(entry.source == source_zone and entry.destination == destination_zone
                   for entry in self.config.nat):
                nat = f" nat-to ({interface})"
        return f"{action} {direction}{log} quick on {interface} {family}{protocol} {hosts}{service}{extra}{nat}{state}"

    def expanded(self, rule, mode):
        families = FAMILIES if rule.family == "both" else (rule.family,)
        for family in families:
            for source_zone in self.zone_names(rule.source.zone, family):
                for destination_zone in self.zone_names(rule.destination.zone, family):
                    source_local = source_zone == self.config.firewall
                    destination_local = destination_zone == self.config.firewall
                    if mode == "local" and (source_local or not destination_local):
                        continue
                    if mode == "origin" and (not source_local or destination_local):
                        continue
                    if mode == "transit" and (source_local or destination_local):
                        continue
                    source = self.addresses(rule.source, source_zone, family)
                    destination = self.addresses(rule.destination, destination_zone, family)
                    if source is None or destination is None:
                        continue
                    source_ifs = tuple(interface for interface in self.zone_interfaces[source_zone]
                                       if interface.network(family))
                    destination_ifs = tuple(interface for interface in self.zone_interfaces[destination_zone]
                                            if interface.network(family))
                    if mode == "local":
                        for interface in source_ifs:
                            yield self.filter(rule, source_zone, destination_zone, family, "in", interface.name, source, destination)
                    elif mode == "origin":
                        for interface in destination_ifs:
                            yield self.filter(rule, source_zone, destination_zone, family, "out", interface.name, source, destination)
                    else:
                        for incoming in source_ifs:
                            yield self.filter(rule, source_zone, destination_zone, family, "in", incoming.name, source, destination)
                            for outgoing in destination_ifs:
                                yield self.filter(rule, source_zone, destination_zone, family, "out", outgoing.name, source, destination,
                                                  " received-on " + incoming.name)

    def rules(self, mode):
        for rule in self.config.rules:
            lines = tuple(self.expanded(rule, mode))
            if lines:
                yield f"# {Path(rule.location.file).name}:{rule.location.line}"
                yield from lines

    def policies(self, mode):
        for number, policy in enumerate(self.config.policies):
            if number == len(self.config.policies) - 1 and policy.source == policy.destination == "all" and policy.action == "DROP" and not policy.log:
                continue
            rule = Rule(policy.action, Selector(policy.source), Selector(policy.destination),
                        policy.family, "any", "-", policy.log, policy.location)
            lines = tuple(self.expanded(rule, mode))
            if lines:
                yield f"# {Path(policy.location.file).name}:{policy.location.line}"
                yield from lines

    def forward_matches(self):
        for number, forward in enumerate(self.config.forwards, 1):
            self.lines.append(f"# {Path(forward.location.file).name}:{forward.location.line}")
            for source_zone in self.zone_names(forward.source.zone, "inet"):
                source = self.addresses(forward.source, source_zone, "inet")
                if source is None:
                    continue
                for interface in self.zone_interfaces[source_zone]:
                    self.lines.append(f"match in on {interface.name} inet proto {forward.protocol} from {source} to ({interface.name}) port {forward.public_port} tag mp_rdr_{number} rdr-to {forward.target} port {forward.target_port}")

    def forward_passes(self):
        for number, forward in enumerate(self.config.forwards, 1):
            rule = Rule("ACCEPT", forward.source, Selector(forward.destination, forward.target),
                        "inet", forward.protocol, forward.target_port, forward.log, forward.location)
            yield f"# {Path(forward.location.file).name}:{forward.location.line}"
            for line in self.expanded(rule, "transit"):
                yield line.replace(" keep state (if-bound)", f" tagged mp_rdr_{number} keep state (if-bound)")

    def run(self):
        self.options()
        self.controls()
        self.guards()
        if self.config.forwards:
            self.section("Redirection; subsequent filters see the translated destination")
            self.forward_matches()
        self.section("Traffic addressed to the firewall")
        self.lines.append('anchor "makepf_local" in to (self) {')
        self.lines.extend("    " + line for line in self.rules("local"))
        self.lines.extend("    " + line for line in self.policies("local"))
        self.lines.extend(("    block in quick all", "}"))
        self.section("Traffic originating on the firewall")
        self.lines.append('anchor "makepf_origin" out from (self) ! received-on any {')
        self.lines.extend("    " + line for line in self.rules("origin"))
        self.lines.extend("    " + line for line in self.policies("origin"))
        self.lines.extend(("    block out quick all", "}"))
        self.section("Forwarded traffic: explicit rules, port forwards, then policies")
        self.lines.extend(self.rules("transit"))
        self.lines.extend(self.forward_passes())
        self.lines.extend(self.policies("transit"))
        return "\n".join(self.lines) + "\n"


def render(config: Config) -> str:
    """Return a deterministic ruleset without reading or changing the host."""
    return _Renderer(config).run()
